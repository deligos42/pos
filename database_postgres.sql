CREATE TABLE recommendation_letters (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no VARCHAR(50) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL,
  generated_by INTEGER DEFAULT NULL,
  generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_recommendation_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_recommendation_generated_by FOREIGN KEY (generated_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL
);

