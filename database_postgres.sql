CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  id_number VARCHAR(50) DEFAULT NULL,
  email VARCHAR(100) DEFAULT NULL UNIQUE,
  role VARCHAR(20) NOT NULL DEFAULT 'cashier' CHECK (role IN ('admin','cashier')),
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  email_verification_code VARCHAR(6) DEFAULT NULL,
  email_verification_expires_at TIMESTAMP DEFAULT NULL,
  email_verification_resend_count INTEGER NOT NULL DEFAULT 0,
  email_verification_last_sent_at TIMESTAMP DEFAULT NULL,
  profile_photo VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  token VARCHAR(128) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_password_resets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

